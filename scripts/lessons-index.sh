#!/usr/bin/env bash
# Generates docs/lessons/INDEX.md from the one-file-per-lesson entries in docs/lessons/.
# Usage: scripts/lessons-index.sh            regenerate docs/lessons/INDEX.md
#        scripts/lessons-index.sh --check    exit 1 if INDEX.md is missing or stale (used by verify.sh)
#        scripts/lessons-index.sh --stdout   write the generated index to stdout without touching the file
#        scripts/lessons-index.sh --merge <theirs-index>  merge an incoming generated index and write to stdout
# Each lesson is docs/lessons/YYYY-MM-DD-slug.md: first line "# Title", then **Trap:**, **Root Cause:**
# and **Rule:** lines. Two PRs never edit the same lesson file; the lessons-index merge driver
# regenerates the index from the merged lesson files.
# OPENSAND_LESSONS_DIR overrides the directory (selftest).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LESSONS_DIR="${OPENSAND_LESSONS_DIR:-$ROOT/docs/lessons}"
INDEX="$LESSONS_DIR/INDEX.md"
MODE="write"
MERGE_INDEX=""

case "${1:-}" in
  "") ;;
  --check) MODE="check" ;;
  --stdout) MODE="stdout" ;;
  --merge)
    MODE="merge"
    if [[ $# -ne 2 ]]; then
      echo "FAIL: --merge needs the incoming generated index path" >&2
      exit 1
    fi
    MERGE_INDEX="$2"
    ;;
  -h|--help)
    sed -n '2,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  *)
    echo "FAIL: unknown argument '$1'" >&2
    echo "Usage: scripts/lessons-index.sh [--check|--stdout|--merge <theirs-index>]" >&2
    exit 1
    ;;
esac

if [[ ! -d "$LESSONS_DIR" ]]; then
  echo "FAIL: lessons directory not found: $LESSONS_DIR" >&2
  exit 1
fi

NAME_RE='^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])-[a-z0-9]+(-[a-z0-9]+)*\.md$'
FAILED=0
ENTRIES=""

while IFS= read -r file; do
  name="$(basename "$file")"
  [[ "$name" == "INDEX.md" ]] && continue
  if [[ ! "$name" =~ $NAME_RE ]]; then
    echo "FAIL: $name is not named YYYY-MM-DD-slug.md (lowercase letters, digits, hyphens)" >&2
    FAILED=1
    continue
  fi
  title="$(sed -n '1p' "$file")"
  if [[ "$title" != "# "?* ]]; then
    echo "FAIL: $name must start with a '# Title' line" >&2
    FAILED=1
    continue
  fi
  for field in "Trap" "Root Cause" "Rule"; do
    if ! grep -qF "**${field}:**" "$file"; then
      echo "FAIL: $name is missing a **${field}:** line" >&2
      FAILED=1
    fi
  done
  ENTRIES+="- ${name:0:10} · [${title#\# }](${name})"$'\n'
done < <(LC_ALL=C find "$LESSONS_DIR" -maxdepth 1 -type f -name '*.md' | LC_ALL=C sort)

if [[ "$FAILED" -ne 0 ]]; then
  exit 1
fi

if [[ "$MODE" == "merge" ]]; then
  if [[ ! -f "$MERGE_INDEX" ]] || ! grep -qF '<!-- GENERATED by scripts/lessons-index.sh.' "$MERGE_INDEX"; then
    echo "FAIL: incoming lessons index is missing or not generated: $MERGE_INDEX" >&2
    exit 1
  fi
  ENTRY_RE='^- [0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01]) · \[.*\]\(([0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])-[a-z0-9]+(-[a-z0-9]+)*\.md)\)$'
  while IFS= read -r line; do
    [[ "$line" == "- "* ]] || continue
    if [[ ! "$line" =~ $ENTRY_RE ]]; then
      echo "FAIL: malformed entry in incoming lessons index: $line" >&2
      exit 1
    fi
    ENTRIES+="$line"$'\n'
  done < "$MERGE_INDEX"
  ENTRIES="$(printf '%s' "$ENTRIES" | LC_ALL=C sort -u)"$'\n'
fi

GENERATED='<!-- GENERATED by scripts/lessons-index.sh. Do not edit; regenerate with: bash scripts/lessons-index.sh -->
# Lessons index

One file per lesson, named `YYYY-MM-DD-slug.md`, each with **Trap**, **Root Cause** and **Rule**.
Entries up to 12.34 live in `AGENTS_LEARNING.md` and are not rewritten.

'"${ENTRIES}"

if [[ "$MODE" == "stdout" || "$MODE" == "merge" ]]; then
  printf '%s' "$GENERATED"
  exit 0
fi

if [[ "$MODE" == "check" ]]; then
  if [[ ! -f "$INDEX" ]]; then
    echo "FAIL: $INDEX is missing. Run: bash scripts/lessons-index.sh" >&2
    exit 1
  fi
  if ! cmp -s <(printf '%s' "$GENERATED") "$INDEX"; then
    echo "FAIL: docs/lessons/INDEX.md is stale. Run: bash scripts/lessons-index.sh" >&2
    exit 1
  fi
  echo "PASS: lessons index is up to date"
  exit 0
fi

TMP="$(mktemp "$LESSONS_DIR/.INDEX.XXXXXX")"
printf '%s' "$GENERATED" > "$TMP"
mv "$TMP" "$INDEX"
echo "Wrote $INDEX"
